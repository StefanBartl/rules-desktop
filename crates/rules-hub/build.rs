// Embeds the built page (`ui/dist`) into the binary.
//
// A build without `ui/dist` embeds nothing and the hub shows the placeholder of the kit; a build
// with it serves the page from memory, with no file to find at run time. Which files count is
// `src/ui_table.rs`, the same file `src/ui.rs` reads a build folder with: the `index.html` and the
// files directly in `assets/`, plain names, a short list of types, none over 4 MiB.
//
// Cargo decides by modification times whether to run a build script again. A folder that was
// moved back into place keeps an old time, and the binary would then carry the page of an earlier
// build. So this script is run by every build (it names a path that is never there, which cargo
// counts as changed), and what it writes holds a hash of the files: the crate is built again
// exactly when the page differs. Build the page (`pnpm build` in `ui/`) before cargo.

use std::fmt::Write as _;
use std::path::PathBuf;

#[allow(dead_code)]
#[path = "src/ui_table.rs"]
mod ui_table;

/// FNV-1a, 64 bit: a fingerprint of the files, not a security measure.
fn fnv(hash: &mut u64, bytes: &[u8]) {
    for b in bytes {
        *hash ^= u64::from(*b);
        *hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
}

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let dist = manifest.join("..").join("..").join("ui").join("dist");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("out dir")).join("ui_embedded.rs");
    // A path that is not there: always "changed", so always run (see above).
    println!("cargo:rerun-if-changed=ui-dist-is-looked-at-by-every-build");

    let entries = ui_table::entries(&dist)
        .unwrap_or_else(|e| panic!("the page in {} cannot be embedded: {e}", dist.display()));

    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    let mut body = String::new();
    for entry in &entries {
        let bytes = std::fs::read(&entry.path).expect("read a file of the page");
        fnv(&mut hash, entry.key.as_bytes());
        fnv(&mut hash, &bytes);
        let canonical = entry
            .path
            .canonicalize()
            .unwrap_or_else(|_| entry.path.clone());
        // `{:?}` escapes the backslashes and quotes of a Windows path.
        writeln!(
            body,
            "    ({:?}, {:?}, include_bytes!({:?})),",
            entry.key,
            entry.content_type,
            canonical.display().to_string()
        )
        .expect("write to a string");
    }

    let mut code = String::new();
    writeln!(code, "// generated by build.rs; the files hash to {hash:016x}").expect("string");
    code.push_str("/// The files of the page in this binary: key, type, bytes.\n");
    code.push_str("pub static EMBEDDED: &[(&str, &str, &[u8])] = &[\n");
    code.push_str(&body);
    code.push_str("];\n");

    // Written only when it differs: an unchanged file does not make the crate build again.
    if std::fs::read_to_string(&out).ok().as_deref() != Some(code.as_str()) {
        std::fs::write(out, code).expect("write the embedded table");
    }
}
